/* SERE Moto - Neon Postgres schema. Applied by src/db.js on every start; every statement is
   idempotent, so an existing database is upgraded rather than recreated.

   This was src/schema.sql, read with fs at boot. A Vercel function is bundled by following the JS
   import graph, so a non-JS asset that merely sits next to the code never reached /var/task and the
   app crashed before it could answer a request. An import is traced; a filesystem path is not. */
export const SCHEMA_SQL = `
/* Timestamps stay TEXT in the same 'YYYY-MM-DD HH24:MI:SS' format the API has always returned.
   datetime(value, ...modifiers) is a compatibility function for the SQLite call sites the queries
   were written against: it accepts 'now', numeric offsets such as '+2 hours' or '-30 minutes',
   'start of day' and 'start of month', and always works in UTC. */
CREATE OR REPLACE FUNCTION datetime(value text DEFAULT 'now', VARIADIC modifiers text[] DEFAULT '{}')
RETURNS text
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  at timestamp;
  modifier text;
BEGIN
  at := CASE
    WHEN value IS NULL OR lower(value) = 'now' THEN (now() AT TIME ZONE 'UTC')
    ELSE value::timestamp
  END;
  FOREACH modifier IN ARRAY modifiers LOOP
    IF modifier = 'start of day' THEN
      at := date_trunc('day', at);
    ELSIF modifier = 'start of month' THEN
      at := date_trunc('month', at);
    ELSIF modifier ~ '^[+-]?[0-9]+ (seconds?|minutes?|hours?|days?)$' THEN
      at := at + modifier::interval;
    ELSE
      RAISE EXCEPTION 'datetime(): unsupported modifier %', modifier;
    END IF;
  END LOOP;
  RETURN to_char(at, 'YYYY-MM-DD HH24:MI:SS');
END;
$$;

/* A rider account is born from an email plus a password (or from Google) and starts life as a
   'draft': only the credential columns are filled. The KYC columns — name, phone, plate, ID, TIN —
   are nullable because the complete-your-details form is what writes them, and filing that form is
   what moves the row from 'draft' to 'pending' and into the admin queue. A draft is not an
   application yet, so it never appears in /api/admin/applications. */
CREATE TABLE IF NOT EXISTS drivers (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           TEXT,
  password_hash   TEXT,
  phone           TEXT,
  name            TEXT,
  plate           TEXT,
  vehicle_type    TEXT    NOT NULL DEFAULT 'moto'
                  CHECK (vehicle_type IN ('moto','car')),
  id_number       TEXT,
  tin_number      TEXT,
  google_id       TEXT,
  status          TEXT    NOT NULL DEFAULT 'draft'
                  CHECK (status IN ('draft','pending','approved','rejected')),
  review_reason   TEXT,
  reviewed_at     TEXT,
  is_admin        INTEGER NOT NULL DEFAULT 0,
  zone            TEXT,
  zones           TEXT    NOT NULL DEFAULT '[]',
  price_per_km    INTEGER CHECK (price_per_km IS NULL OR price_per_km BETWEEN 100 AND 2000),
  services        TEXT    CHECK (services IS NULL OR services IN ('ride','delivery','both')),
  capacity        INTEGER CHECK (capacity IS NULL OR capacity BETWEEN 1 AND 8),
  available_slots TEXT    NOT NULL DEFAULT '[]',
  is_online       INTEGER NOT NULL DEFAULT 0,
  lat             DOUBLE PRECISION,
  lng             DOUBLE PRECISION,
  loc_at          TEXT,
  on_trip         INTEGER NOT NULL DEFAULT 0,
  rating_sum      INTEGER NOT NULL DEFAULT 0,
  rating_count    INTEGER NOT NULL DEFAULT 0,
  created_at      TEXT    NOT NULL DEFAULT (datetime('now')),
  tin_status      TEXT    NOT NULL DEFAULT 'unchecked',
  id_status       TEXT    NOT NULL DEFAULT 'unchecked',
  phone_status    TEXT    NOT NULL DEFAULT 'unchecked',
  kyc_at          TEXT,
  loc_code        TEXT,
  loc_level       INTEGER,
  province_code   TEXT,
  district_code   TEXT,
  sector_code     TEXT,
  live_code       TEXT,
  CONSTRAINT drivers_phone_key UNIQUE (phone),
  CONSTRAINT drivers_plate_key UNIQUE (plate),
  CONSTRAINT drivers_id_number_key UNIQUE (id_number),
  CONSTRAINT drivers_tin_number_key UNIQUE (tin_number),
  CONSTRAINT drivers_google_id_key UNIQUE (google_id),
  CONSTRAINT drivers_email_key UNIQUE (email)
);

/* A database created before email sign-in has no credential column at all, and CREATE TABLE IF NOT
   EXISTS will not add one to the table it skips. These two come before everything else that names
   email — the login index and the UNIQUE constraint below — because Postgres refuses a statement
   over a column that is not there, and a throw here fails the import of src/db.js, which turns every
   single /api call into a 500. A current database already has both, so these are no-ops. */
ALTER TABLE drivers ADD COLUMN IF NOT EXISTS email         TEXT;
ALTER TABLE drivers ADD COLUMN IF NOT EXISTS password_hash TEXT;

CREATE INDEX IF NOT EXISTS idx_drivers_online ON drivers (is_online, zone);
CREATE INDEX IF NOT EXISTS idx_drivers_type   ON drivers (vehicle_type, services);
CREATE INDEX IF NOT EXISTS idx_drivers_status ON drivers (status, created_at);
CREATE INDEX IF NOT EXISTS idx_drivers_loc ON drivers (is_online, loc_at);
CREATE INDEX IF NOT EXISTS idx_drivers_district ON drivers (district_code, is_online);
CREATE INDEX IF NOT EXISTS idx_drivers_live ON drivers (live_code, is_online);
/* An account exists as soon as an email is claimed, so the login lookup needs it indexed. */
CREATE INDEX IF NOT EXISTS idx_drivers_email ON drivers (email);

/* The rest of the shape a database created before email sign-in has to be loosened into. Every
   statement here is a no-op on a database that already looks like the CREATE TABLE above, so booting
   against the live Neon database changes it once and never again — except for the two CHECKs, which
   Postgres only lets you replace, so they are dropped and re-added with the same name. */
ALTER TABLE drivers ALTER COLUMN phone DROP NOT NULL;
ALTER TABLE drivers ALTER COLUMN name  DROP NOT NULL;
ALTER TABLE drivers ALTER COLUMN plate  DROP NOT NULL;
ALTER TABLE drivers ALTER COLUMN vehicle_type SET DEFAULT 'moto';
ALTER TABLE drivers ALTER COLUMN status SET DEFAULT 'draft';
ALTER TABLE drivers DROP CONSTRAINT IF EXISTS drivers_status_check;
ALTER TABLE drivers ADD CONSTRAINT drivers_status_check
        CHECK (status IN ('draft','pending','approved','rejected'));
ALTER TABLE drivers DROP CONSTRAINT IF EXISTS drivers_email_key;
ALTER TABLE drivers ADD CONSTRAINT drivers_email_key UNIQUE (email);

/* Identity documents a rider uploads before approval. The file lives in S3; this row is the
   pointer, the provider's answer when the upload was verified, and the admin's review state.
   A trading licence is the one document issued as a paper PDF, so it is the only kind that may
   arrive as application/pdf. */
CREATE TABLE IF NOT EXISTS driver_documents (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id    INTEGER NOT NULL REFERENCES drivers (id) ON DELETE CASCADE,
  kind         TEXT    NOT NULL CHECK (kind IN ('national_id','driving_licence','plate','trading_licence')),
  object_key   TEXT    NOT NULL UNIQUE,
  content_type TEXT    NOT NULL,
  bytes        INTEGER NOT NULL DEFAULT 0 CHECK (bytes >= 0),
  status       TEXT    NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending','uploaded','rejected')),
  note         TEXT,
  uploaded_at  TEXT,
  created_at   TEXT    NOT NULL DEFAULT (datetime('now')),
  CONSTRAINT driver_documents_driver_id_kind_key UNIQUE (driver_id, kind)
);

CREATE INDEX IF NOT EXISTS idx_driver_documents_driver ON driver_documents (driver_id, kind);

/* A database created before the trading licence existed still has the old four-kind CHECK, and
   Postgres only lets you replace a CHECK by dropping it first. */
ALTER TABLE driver_documents DROP CONSTRAINT IF EXISTS driver_documents_kind_check;
ALTER TABLE driver_documents ADD CONSTRAINT driver_documents_kind_check
        CHECK (kind IN ('national_id','driving_licence','plate','trading_licence'));

/* Zone names are geocoded once and reused, so a client search costs no external call. */
CREATE TABLE IF NOT EXISTS places (
  key        TEXT    PRIMARY KEY,
  lat        DOUBLE PRECISION NOT NULL,
  lng        DOUBLE PRECISION NOT NULL,
  label      TEXT    NOT NULL,
  created_at TEXT    NOT NULL DEFAULT (datetime('now'))
);

/* Measured road distances are cached per coordinate pair; the public OSRM server is rate limited. */
CREATE TABLE IF NOT EXISTS routes (
  key         TEXT    PRIMARY KEY,
  distance_km DOUBLE PRECISION NOT NULL,
  created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
);

/* A passenger is a verified phone number, nothing else: no password, no KYC, no plate. */
CREATE TABLE IF NOT EXISTS passengers (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone         TEXT    NOT NULL UNIQUE,
  name          TEXT,
  email         TEXT,
  created_at    TEXT    NOT NULL DEFAULT (datetime('now')),
  last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS ride_requests (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id    INTEGER NOT NULL REFERENCES drivers (id) ON DELETE CASCADE,
  client_name  TEXT    NOT NULL,
  client_phone TEXT    NOT NULL,
  kind         TEXT    NOT NULL CHECK (kind IN ('ride','delivery')),
  origin       TEXT    NOT NULL,
  destination  TEXT    NOT NULL,
  scheduled_at TEXT,
  passengers   INTEGER NOT NULL DEFAULT 1 CHECK (passengers BETWEEN 1 AND 8),
  note         TEXT,
  status       TEXT    NOT NULL DEFAULT 'new'
               CHECK (status IN ('new','seen','accepted','completed','declined','cancelled')),
  distance_km  DOUBLE PRECISION,
  distance_source TEXT,
  fare_rwf     INTEGER,
  fare_basis   TEXT,
  passenger_id INTEGER REFERENCES passengers (id) ON DELETE SET NULL,
  created_at   TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_requests_driver ON ride_requests (driver_id, status);

CREATE TABLE IF NOT EXISTS passenger_places (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passengers (id) ON DELETE CASCADE,
  label        TEXT    NOT NULL,
  address      TEXT    NOT NULL,
  lat          DOUBLE PRECISION,
  lng          DOUBLE PRECISION,
  created_at   TEXT    NOT NULL DEFAULT (datetime('now')),
  CONSTRAINT passenger_places_passenger_id_label_key UNIQUE (passenger_id, label)
);

/* One rating per completed trip, so a passenger cannot rate the same ride twice. */
CREATE TABLE IF NOT EXISTS trip_ratings (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id   INTEGER NOT NULL REFERENCES ride_requests (id) ON DELETE CASCADE,
  passenger_id INTEGER NOT NULL REFERENCES passengers (id) ON DELETE CASCADE,
  driver_id    INTEGER NOT NULL REFERENCES drivers (id) ON DELETE CASCADE,
  stars        INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
  comment      TEXT,
  created_at   TEXT    NOT NULL DEFAULT (datetime('now')),
  UNIQUE (request_id)
);

CREATE INDEX IF NOT EXISTS idx_requests_client ON ride_requests (client_phone, id);
CREATE INDEX IF NOT EXISTS idx_places_passenger ON passenger_places (passenger_id);
CREATE INDEX IF NOT EXISTS idx_ratings_driver ON trip_ratings (driver_id, stars);

CREATE TABLE IF NOT EXISTS payments (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id        INTEGER NOT NULL REFERENCES ride_requests (id) ON DELETE CASCADE,
  provider          TEXT    NOT NULL CHECK (provider IN ('paystack','mtn_momo')),
  provider_reference TEXT   NOT NULL UNIQUE,
  payer_phone       TEXT,
  payer_email       TEXT,
  amount_rwf        INTEGER NOT NULL CHECK (amount_rwf > 0),
  platform_fee_rwf  INTEGER NOT NULL CHECK (platform_fee_rwf >= 0),
  driver_payout_rwf INTEGER NOT NULL CHECK (driver_payout_rwf >= 0),
  status            TEXT    NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','paid','failed','refunded')),
  checkout_url      TEXT,
  initiate_response TEXT,
  confirm_response  TEXT,
  confirmed_at      TEXT,
  created_at        TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_payments_request ON payments (request_id, status);

CREATE TABLE IF NOT EXISTS webhook_events (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider     TEXT NOT NULL,
  external_id  TEXT NOT NULL,
  payload      TEXT NOT NULL,
  error        TEXT,
  received_at  TEXT NOT NULL DEFAULT (datetime('now')),
  processed_at TEXT,
  CONSTRAINT webhook_events_provider_external_id_key UNIQUE (provider, external_id)
);

/* What RRA, NIDA and the number-check service answered, keyed by the value asked about.
   A verdict is reused for 24 hours so an application is never billed twice for one lookup,
   and \`note\` keeps what the provider actually returned when it said no. */
CREATE TABLE IF NOT EXISTS tin_checks (
  tin        TEXT    PRIMARY KEY,
  valid      INTEGER NOT NULL,
  taxpayer   TEXT,
  source     TEXT    NOT NULL,
  note       TEXT,
  checked_at TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS id_checks (
  id_number  TEXT    PRIMARY KEY,
  match      INTEGER NOT NULL,
  name       TEXT,
  source     TEXT    NOT NULL,
  note       TEXT,
  checked_at TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS phone_checks (
  phone      TEXT    PRIMARY KEY,
  valid      INTEGER NOT NULL,
  operator   TEXT,
  source     TEXT    NOT NULL,
  note       TEXT,
  checked_at TEXT    NOT NULL DEFAULT (datetime('now'))
);

/* Rwanda's five legal administrative levels, one row per division:
   1 Intara, 2 Akarere, 3 Umurenge, 4 Akagari, 5 Umudugudu.
   A code is its parent's code plus its own slug, so the tree can be walked either way.
   lat/lng is the OpenStreetMap centroid when one is known — a rough position for "the rider is
   around Musanze", never a boundary. */
CREATE TABLE IF NOT EXISTS locations (
  code        TEXT    PRIMARY KEY,
  level       INTEGER NOT NULL CHECK (level BETWEEN 1 AND 5),
  name        TEXT    NOT NULL,
  name_rw     TEXT    NOT NULL,
  parent_code TEXT    REFERENCES locations (code) ON DELETE CASCADE,
  lat         DOUBLE PRECISION,
  lng         DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_locations_parent ON locations (parent_code, name);
CREATE INDEX IF NOT EXISTS idx_locations_level  ON locations (level, name);
`;
