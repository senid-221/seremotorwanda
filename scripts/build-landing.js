/* Regenerate src/landing.js from public/index.html.
   A serverless function bundle carries only what the JS import graph reaches, and this project's Vercel
   router hands `/` to the function instead of to public/index.html — so the landing page has to be
   importable to be servable. Run `npm run landing` after editing public/index.html; the smoke suite
   fails if the module and the file ever disagree. */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'public', 'index.html'), 'utf8');
const body = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const out = `/* public/index.html, as one string. Generated by scripts/build-landing.js — edit the HTML,
   then run \`npm run landing\`. src/app.js answers GET / with this when the deploy has no public/
   directory to read, which is what a serverless bundle is. */
export const LANDING_HTML = \`${body}\`;
`;

fs.writeFileSync(path.join(ROOT, 'src', 'landing.js'), out);
console.log(`[landing] public/index.html (${html.length} bytes) -> src/landing.js (${out.length} bytes)`);
